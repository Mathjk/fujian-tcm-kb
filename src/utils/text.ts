// 把段内连排的分点标记拆为独立行：
//  - （1）（2）/（一）（二） 全半角括号数字
//  - ①②③… 圈码
//  - 。；： 之后出现的「XX症状：」「局部症状有」等小标题句
const HEAD_WORDS =
  "症状|体征|表现|特点|治法|方药|用法|制法|主治|功效|禁忌|注意|处理|治疗|诊断|鉴别|病机|病因|预后|按语|附方|疗程|适应症|局部|全身";
const ITEM_MARK = new RegExp(
  "(?=[（(][0-9０-９一二三四五六七八九十]+[)）])" +
    "|(?=[①②③④⑤⑥⑦⑧⑨⑩])" +
    "|(?<=[。；：])(?=[^。；，、]{0,10}(?:" + HEAD_WORDS + "))",
  "g"
);

export const splitItems = (t: string): string[] =>
  t.split(ITEM_MARK).map((s) => s.trim()).filter(Boolean);
